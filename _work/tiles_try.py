"""Try several 8x8 wall/floor/player tile designs and render a comparison sheet."""
import sys, os
sys.path.insert(0, r"D:\GIT\cabnetBoy\_work")
import rogue_preview as R
from PIL import Image, ImageDraw

CAND = {
 "A dither50": dict(
    wall=[0xAA,0x55,0xAA,0x55,0xAA,0x55,0xAA,0x55],
    floor=[0x00,0x20,0x00,0x02,0x00,0x00,0x88,0x00]),
 "B dither25": dict(
    wall=[0x88,0x22,0x88,0x22,0x88,0x22,0x88,0x22],
    floor=[0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00]),
 "C bricks": dict(
    wall=[0xFF,0x00,0x00,0xFF,0xEF,0x00,0x00,0xFF],
    floor=[0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00]),
 "D bricks2": dict(
    wall=[0xFF,0x81,0x81,0xFF,0x18,0x18,0xFF,0x81],
    floor=[0x00,0x10,0x00,0x00,0x00,0x00,0x40,0x00]),
 "E dither12": dict(
    wall=[0x80,0x00,0x08,0x00,0x80,0x00,0x08,0x00],
    floor=[0x00,0x00,0x20,0x00,0x00,0x02,0x00,0x00]),
}

PLAYER = [0x3C,0x42,0x42,0x5A,0x5A,0x42,0x42,0x3C]
MON = {
    'R': [0x00,0x6C,0x92,0x82,0xBA,0x82,0x44,0x38],
    'G': [0x00,0x3C,0x66,0x42,0x5A,0x42,0x42,0x66],
    'S': [0x00,0x18,0x24,0x42,0x5A,0x24,0x18,0x00],
    'O': [0x00,0x3C,0x42,0x5A,0x5A,0x42,0x3C,0x00],
}

def sheet():
    names = list(CAND)
    g = R.G(0xACE1); g.gen_level(); g.fov()
    imgs = []
    for n in names:
        R.TILES = [ [0]*8, CAND[n]["floor"], CAND[n]["wall"], [0]*8, PLAYER ]
        imgs.append(R.render(g, "WALL TEST"))
    W, H = 128*3, 64*3
    out = Image.new("RGB", (W*len(names), H+14), (30,30,30))
    d = ImageDraw.Draw(out)
    for i, (n, im) in enumerate(zip(names, imgs)):
        out.paste(im.convert("RGB").resize((W,H), Image.NEAREST), (i*W, 14))
        d.text((i*W+4, 2), n, fill=(255,255,0))
    return out

if __name__ == "__main__":
    out = r"D:\GIT\cabnetBoy\_work\rogue\tiles_compare.png"
    os.makedirs(os.path.dirname(out), exist_ok=True)
    sheet().save(out)
    print("wrote", out)
